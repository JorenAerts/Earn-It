#!/usr/bin/env python3
"""Writes Android translations (app/src/main/res/values-<lang>/strings.xml) from the iOS catalog.

One source of truth: every English string in values/strings.xml is looked up in
iOS/App/Localizable.xcstrings (same English text = same key; placeholders %1$d / %1$s map to
iOS %lld / %@). Android-only texts come from scripts/l10n_android/<code>.json ({"name": "text"}).
Prints what is still missing per language. Run from Android/:

    python3 scripts/android_strings.py
"""
import json, pathlib, re, sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
CATALOG = ROOT.parent / "iOS/App/Localizable.xcstrings"
EXTRA = ROOT / "scripts/l10n_android"
# iOS language → Android resource folder(s).
LANGS = {"nl": ["nl"], "fr": ["fr"], "de": ["de"], "es": ["es"], "it": ["it"],
         "pt-BR": ["pt-rBR"], "pt-PT": ["pt-rPT", "pt"]}

ANDROID_ARG = re.compile(r"%(\d+)\$([ds])")
IOS_ARG = re.compile(r"%(?:(\d+)\$)?(lld|ld|d|@)")


def unescape(text):
    return re.sub(r"\\(['\"@?])", r"\1", text).replace("\\n", "\n")


def escape(text):
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return "\\" + text if text[:1] in "@?" else text


def ios_key(english):
    """'Solve %1$d problems in a row.' → 'Solve %lld problems in a row.'"""
    return ANDROID_ARG.sub(lambda m: "%lld" if m.group(2) == "d" else "%@", english)


def to_android(translation, arg_types):
    counter = 0

    def repl(m):
        nonlocal counter
        if m.group(1):
            n = int(m.group(1))
        else:
            counter += 1
            n = counter
        kind = arg_types.get(n, "d" if m.group(2) != "@" else "s")
        return f"%{n}${kind}"
    return IOS_ARG.sub(repl, translation)


def lookup(catalog, key, lang):
    loc = catalog.get(key, {}).get("localizations", {}).get(lang)
    if not loc:
        return None
    if "stringUnit" in loc:
        return loc["stringUnit"].get("value")
    plural = loc.get("variations", {}).get("plural", {})
    return (plural.get("other") or {}).get("stringUnit", {}).get("value")


def main():
    catalog = json.loads(CATALOG.read_text())["strings"]
    tree = ET.parse(RES / "values/strings.xml")
    english = [(e.get("name"), unescape(e.text or "")) for e in tree.getroot().findall("string")
               if e.get("translatable") != "false"]
    missing_total = 0
    for lang, folders in LANGS.items():
        extra_file = EXTRA / f"{lang}.json"
        extra = json.loads(extra_file.read_text()) if extra_file.exists() else {}
        out, missing = [], []
        for name, text in english:
            arg_types = {int(n): t for n, t in ANDROID_ARG.findall(text)}
            value = extra.get(name)
            if value is None:
                found = lookup(catalog, ios_key(text), lang)
                value = to_android(found, arg_types) if found else None
            if value is None:
                missing.append(name)
                continue
            out.append(f'    <string name="{name}">{escape(value).replace("&", "&amp;").replace("<", "&lt;")}</string>')
        body = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/android_strings.py. Do not edit. -->\n<resources>\n' + "\n".join(out) + "\n</resources>\n"
        for folder in folders:
            path = RES / f"values-{folder}/strings.xml"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
        print(f"{lang}: {len(out)}/{len(english)} translated" + (f", missing: {', '.join(missing)}" if missing else ""))
        missing_total += len(missing)
    return 1 if "--strict" in sys.argv and missing_total else 0


if __name__ == "__main__":
    sys.exit(main())
